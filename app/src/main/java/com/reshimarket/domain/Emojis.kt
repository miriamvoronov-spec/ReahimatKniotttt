    /** מסיר ניקוד וטעמים ומקצץ רווחים */
    fun norm(s: String): String =
        s.replace(Regex("[\\u0591-\\u05C7]"), "").trim().replace(Regex("\\s+"), " ")

    /** אותיות סופיות לרגילות, כדי ש"מעדן" יתפוס גם "מעדנים" */
    private fun fold(s: String): String =
        s.replace('ך', 'כ').replace('ם', 'מ').replace('ן', 'נ').replace('ף', 'פ').replace('ץ', 'צ')
            .replace('״', '"').replace('׳', '\'')

    private fun pick(map: List<Pair<String, String>>, name: String): String? {
        val n = fold(norm(name))
        if (n.isEmpty()) return null
        val words = n.split(' ', '-', ',', '.', '/').filter { it.isNotEmpty() }
        for ((k, e) in map) {
            if (k.startsWith("=")) {
                if (words.contains(fold(k.substring(1)))) return e
            } else if (n.contains(fold(k))) return e
        }
        return null
    }

